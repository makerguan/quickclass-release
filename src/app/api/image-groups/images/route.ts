import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { verifyToken } from "@/lib/auth";
import {
  ensureGroupDir,
  deleteImageFile,
  generateImageDescription,
} from "@/lib/image-library";

const ALLOWED_EXT = ["jpg", "jpeg", "png", "gif", "webp"];
const MAX_SIZE_MB = 10;

function getExt(filename: string): string {
  const idx = filename.lastIndexOf(".");
  return idx >= 0 ? filename.slice(idx + 1).toLowerCase() : "";
}

// POST: 上传图片到组（自动生成描述，失败由教师手填）
export async function POST(req: NextRequest) {
  try {
    const token = req.headers.get("authorization")?.replace("Bearer ", "");
    if (!token) return NextResponse.json({ error: "未登录" }, { status: 401 });
    const payload = await verifyToken(token);
    if (!payload || payload.role !== "TEACHER")
      return NextResponse.json({ error: "无权限" }, { status: 403 });

    const formData = await req.formData();
    const groupId = formData.get("groupId") as string;
    const file = formData.get("file") as File | null;
    const manualDescription = (formData.get("description") as string) || "";

    if (!groupId) return NextResponse.json({ error: "缺少图片组 ID" }, { status: 400 });
    if (!file) return NextResponse.json({ error: "请选择图片文件" }, { status: 400 });

    const group = await prisma.imageGroup.findUnique({ where: { id: groupId } });
    if (!group || group.teacherId !== String(payload.userId)) {
      return NextResponse.json({ error: "无权限" }, { status: 403 });
    }

    const ext = getExt(file.name);
    if (!ALLOWED_EXT.includes(ext)) {
      return NextResponse.json(
        { error: `不支持的图片格式（允许：${ALLOWED_EXT.join("/")}）` },
        { status: 400 }
      );
    }
    if (file.size > MAX_SIZE_MB * 1024 * 1024) {
      return NextResponse.json(
        { error: `图片大小超过限制（上限 ${MAX_SIZE_MB}MB）` },
        { status: 400 }
      );
    }
    if (file.size === 0) {
      return NextResponse.json({ error: "文件内容为空" }, { status: 400 });
    }

    // 落盘
    const buffer = Buffer.from(await file.arrayBuffer());
    const dir = ensureGroupDir(groupId);
    const filename = `${Date.now()}-${Math.random().toString(36).slice(2, 10)}.${ext}`;
    const fs = await import("fs");
    const path = await import("path");
    fs.writeFileSync(path.join(dir, filename), buffer);

    // 描述：教师已填优先；否则用全局 AI 模型自动生成（失败留空）
    let description = manualDescription.trim();
    let autoGenerated = false;
    if (!description) {
      const mediaType = file.type || `image/${ext === "jpg" ? "jpeg" : ext}`;
      const generated = await generateImageDescription(buffer.toString("base64"), mediaType);
      if (generated) {
        description = generated;
        autoGenerated = true;
      }
    }

    const image = await prisma.imageAsset.create({
      data: {
        groupId,
        filename,
        originalName: file.name,
        description,
        fileType: ext,
        fileSize: file.size,
      },
    });

    // 更新组时间戳（列表按 updatedAt 排序）
    await prisma.imageGroup.update({
      where: { id: groupId },
      data: { updatedAt: new Date() },
    });

    return NextResponse.json({ ...image, autoGenerated });
  } catch (error) {
    console.error("Upload image error:", error);
    const msg = error instanceof Error ? error.message : "服务器错误";
    return NextResponse.json({ error: msg }, { status: 500 });
  }
}

// PATCH: 更新图片描述
export async function PATCH(req: NextRequest) {
  try {
    const token = req.headers.get("authorization")?.replace("Bearer ", "");
    if (!token) return NextResponse.json({ error: "未登录" }, { status: 401 });
    const payload = await verifyToken(token);
    if (!payload || payload.role !== "TEACHER")
      return NextResponse.json({ error: "无权限" }, { status: 403 });

    const { id, description } = await req.json();
    if (!id || typeof description !== "string") {
      return NextResponse.json({ error: "参数不完整" }, { status: 400 });
    }

    const image = await prisma.imageAsset.findUnique({
      where: { id },
      include: { ImageGroup: { select: { teacherId: true } } },
    });
    if (!image || image.ImageGroup.teacherId !== String(payload.userId)) {
      return NextResponse.json({ error: "无权限" }, { status: 403 });
    }

    const updated = await prisma.imageAsset.update({
      where: { id },
      data: { description: description.trim().slice(0, 100) },
    });
    return NextResponse.json(updated);
  } catch (error) {
    console.error("Update image error:", error);
    const msg = error instanceof Error ? error.message : "服务器错误";
    return NextResponse.json({ error: msg }, { status: 500 });
  }
}

// DELETE: 删除单张图片（记录 + 物理文件，组保留）
export async function DELETE(req: NextRequest) {
  try {
    const token = req.headers.get("authorization")?.replace("Bearer ", "");
    if (!token) return NextResponse.json({ error: "未登录" }, { status: 401 });
    const payload = await verifyToken(token);
    if (!payload || payload.role !== "TEACHER")
      return NextResponse.json({ error: "无权限" }, { status: 403 });

    const { searchParams } = new URL(req.url);
    const id = searchParams.get("id");
    if (!id) return NextResponse.json({ error: "缺少 ID" }, { status: 400 });

    const image = await prisma.imageAsset.findUnique({
      where: { id },
      include: { ImageGroup: { select: { teacherId: true } } },
    });
    if (!image || image.ImageGroup.teacherId !== String(payload.userId)) {
      return NextResponse.json({ error: "无权限" }, { status: 403 });
    }

    await prisma.imageAsset.delete({ where: { id } });
    deleteImageFile(image.groupId, image.filename);
    return NextResponse.json({ success: true });
  } catch (error) {
    console.error("Delete image error:", error);
    const msg = error instanceof Error ? error.message : "服务器错误";
    return NextResponse.json({ error: msg }, { status: 500 });
  }
}
