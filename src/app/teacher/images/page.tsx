"use client";

import { useEffect, useState, useRef } from "react";
import {
  Button,
  Card,
  Dialog,
  Input,
  MessagePlugin,
  Tag,
  Textarea,
  Loading,
  Pagination,
  InputNumber,
} from "tdesign-react";
import {
  AddIcon,
  DeleteIcon,
  BrowseIcon,
  CheckCircleIcon,
  StopCircleIcon,
  UploadIcon,
  ImageIcon,
} from "tdesign-icons-react";
import TeacherLayout from "@/components/layout/TeacherLayout";

interface ImageAsset {
  id: string;
  groupId: string;
  filename: string;
  originalName: string;
  description: string;
  fileType: string;
  fileSize: number;
  createdAt: string;
  autoGenerated?: boolean;
}

interface ImageGroup {
  id: string;
  name: string;
  description: string | null;
  enabled: boolean;
  images: ImageAsset[];
  createdAt: string;
  referencedBy?: { id: string; title: string }[];
}

function formatFileSize(bytes: number): string {
  if (bytes < 1024) return bytes + " B";
  if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + " KB";
  return (bytes / (1024 * 1024)).toFixed(1) + " MB";
}

/** 教师端缩略图 URL（带 token） */
function thumbUrl(id: string): string {
  const token = typeof window !== "undefined" ? localStorage.getItem("token") || "" : "";
  return `/api/images/${id}?token=${encodeURIComponent(token)}`;
}

export default function ImageLibraryPage() {
  const [list, setList] = useState<ImageGroup[]>([]);
  const [loading, setLoading] = useState(true);
  const [pageSize, setPageSize] = useState<number>(10);
  const [currentPage, setCurrentPage] = useState<number>(1);
  const [search, setSearch] = useState("");

  // 组表单
  const [formVisible, setFormVisible] = useState(false);
  const [editing, setEditing] = useState<ImageGroup | null>(null);
  const [formName, setFormName] = useState("");
  const [formDesc, setFormDesc] = useState("");
  const [saving, setSaving] = useState(false);

  // 组详情（图片管理）
  const [detailGroup, setDetailGroup] = useState<ImageGroup | null>(null);
  const [uploading, setUploading] = useState(false);
  const [descDrafts, setDescDrafts] = useState<Record<string, string>>({});
  const [deleteGroupTarget, setDeleteGroupTarget] = useState<ImageGroup | null>(null);
  const [deleting, setDeleting] = useState(false);
  const fileInputRef = useRef<HTMLInputElement>(null);

  // 图片放大预览
  const [previewImage, setPreviewImage] = useState<ImageAsset | null>(null);

  useEffect(() => {
    fetchList();
  }, []);

  const fetchList = async () => {
    try {
      const token = localStorage.getItem("token");
      const res = await fetch("/api/image-groups", {
        headers: { Authorization: `Bearer ${token}` },
      });
      if (res.ok) setList(await res.json());
    } catch {
      console.error("获取图片组失败");
    } finally {
      setLoading(false);
    }
  };

  const resetForm = () => {
    setFormName("");
    setFormDesc("");
    setEditing(null);
  };

  const openCreate = () => {
    resetForm();
    setFormVisible(true);
  };

  const openEdit = (g: ImageGroup) => {
    setEditing(g);
    setFormName(g.name);
    setFormDesc(g.description || "");
    setFormVisible(true);
  };

  const handleSaveGroup = async () => {
    if (!formName.trim()) {
      MessagePlugin.error("请填写图片组名称");
      return;
    }
    setSaving(true);
    try {
      const token = localStorage.getItem("token");
      const res = await fetch("/api/image-groups", {
        method: editing ? "PUT" : "POST",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
        body: JSON.stringify({ id: editing?.id, name: formName, description: formDesc }),
      });
      if (res.ok) {
        MessagePlugin.success(editing ? "图片组已更新" : "图片组已创建");
        setFormVisible(false);
        resetForm();
        fetchList();
      } else {
        const data = await res.json().catch(() => ({}));
        MessagePlugin.error(data.error || "保存失败");
      }
    } catch {
      MessagePlugin.error("网络错误");
    } finally {
      setSaving(false);
    }
  };

  const handleToggleEnabled = async (g: ImageGroup) => {
    try {
      const token = localStorage.getItem("token");
      const res = await fetch("/api/image-groups", {
        method: "PATCH",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
        body: JSON.stringify({ id: g.id, enabled: !g.enabled }),
      });
      if (res.ok) {
        MessagePlugin.success(g.enabled ? "已禁用" : "已启用");
        fetchList();
      } else {
        MessagePlugin.error("操作失败");
      }
    } catch {
      MessagePlugin.error("网络错误");
    }
  };

  const handleDeleteGroup = async (id: string) => {
    setDeleting(true);
    try {
      const token = localStorage.getItem("token");
      const res = await fetch(`/api/image-groups?id=${id}`, {
        method: "DELETE",
        headers: { Authorization: `Bearer ${token}` },
      });
      if (res.ok) {
        MessagePlugin.success("已删除");
        setDeleteGroupTarget(null);
        fetchList();
      } else {
        MessagePlugin.error("删除失败");
      }
    } catch {
      MessagePlugin.error("网络错误");
    } finally {
      setDeleting(false);
    }
  };

  const openDetail = (g: ImageGroup) => {
    setDetailGroup(g);
    setDescDrafts({});
  };

  // 刷新详情组数据（上传/改描述/删图后）
  const refreshDetail = async () => {
    const token = localStorage.getItem("token");
    const res = await fetch("/api/image-groups", {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (res.ok) {
      const groups: ImageGroup[] = await res.json();
      setList(groups);
      if (detailGroup) {
        const fresh = groups.find((g) => g.id === detailGroup.id);
        setDetailGroup(fresh || null);
      }
    }
  };

  const handleUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const files = e.target.files;
    if (!files || files.length === 0 || !detailGroup) return;
    setUploading(true);
    const token = localStorage.getItem("token");
    let ok = 0;
    let fail = 0;
    let autoDesc = 0;
    const noDescFiles: string[] = [];
    try {
      for (const file of Array.from(files)) {
        try {
          const formData = new FormData();
          formData.append("groupId", detailGroup.id);
          formData.append("file", file);
          const res = await fetch("/api/image-groups/images", {
            method: "POST",
            headers: { Authorization: `Bearer ${token}` },
            body: formData,
          });
          if (res.ok) {
            ok++;
            const data = await res.json();
            if (data.autoGenerated) autoDesc++;
            else if (!data.description) noDescFiles.push(file.name);
          } else {
            fail++;
            const data = await res.json().catch(() => ({}));
            MessagePlugin.error(`${file.name}：${data.error || "上传失败"}`);
          }
        } catch {
          fail++;
        }
      }
      if (ok > 0) {
        let msg = `已上传 ${ok} 张图片`;
        if (autoDesc > 0) msg += `（${autoDesc} 张已自动生成描述）`;
        if (fail > 0) msg += `，${fail} 张失败`;
        if (noDescFiles.length > 0) {
          // 当前全局 AI 模型不支持看图（如 DeepSeek 纯文本模型），提示教师手填
          MessagePlugin.warning(
            `${msg}；其中 ${noDescFiles.length} 张未自动生成描述（当前 AI 模型不支持图片理解），请在下方手动填写描述`
          );
        } else {
          MessagePlugin.success(msg);
        }
      }
      await refreshDetail();
    } finally {
      setUploading(false);
      if (fileInputRef.current) fileInputRef.current.value = "";
    }
  };

  const handleSaveDesc = async (image: ImageAsset) => {
    const draft = descDrafts[image.id];
    if (draft === undefined || draft === image.description) return;
    try {
      const token = localStorage.getItem("token");
      const res = await fetch("/api/image-groups/images", {
        method: "PATCH",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
        body: JSON.stringify({ id: image.id, description: draft }),
      });
      if (res.ok) {
        MessagePlugin.success("描述已保存");
        await refreshDetail();
      } else {
        MessagePlugin.error("保存失败");
      }
    } catch {
      MessagePlugin.error("网络错误");
    }
  };

  const handleDeleteImage = async (image: ImageAsset) => {
    try {
      const token = localStorage.getItem("token");
      const res = await fetch(`/api/image-groups/images?id=${image.id}`, {
        method: "DELETE",
        headers: { Authorization: `Bearer ${token}` },
      });
      if (res.ok) {
        MessagePlugin.success("已删除");
        await refreshDetail();
      } else {
        MessagePlugin.error("删除失败");
      }
    } catch {
      MessagePlugin.error("网络错误");
    }
  };

  const filteredList = search.trim()
    ? list.filter(
        (g) =>
          g.name.toLowerCase().includes(search.toLowerCase()) ||
          (g.description || "").toLowerCase().includes(search.toLowerCase())
      )
    : list;

  const totalPages = Math.max(1, Math.ceil(filteredList.length / pageSize));
  const safePage = Math.min(currentPage, totalPages);
  const pagedList = filteredList.slice((safePage - 1) * pageSize, safePage * pageSize);

  return (
    <TeacherLayout>
      <div className="space-y-6 pb-8">
        <div className="flex justify-between items-center">
          <div>
            <h2 className="text-xl font-semibold text-[#1A1A1A]">🖼️ 图片仓库管理</h2>
          </div>
          <div className="flex items-center gap-2">
            <Input
              value={search}
              onChange={(v) => { setSearch(v as string); setCurrentPage(1); }}
              placeholder="搜索图片组名称或描述"
              className="w-48"
              clearable
            />
            <Button theme="primary" icon={<AddIcon />} onClick={openCreate}>
              新建图片组
            </Button>
          </div>
        </div>

        {loading ? (
          <div className="text-center text-gray-400 py-12">加载中...</div>
        ) : list.length === 0 ? (
          <Card>
            <div className="text-center py-12 text-gray-400">
              <p className="text-lg mb-2">🖼️</p>
              <p>暂无图片组</p>
              <p className="text-sm mt-2">点击「新建图片组」创建您的第一个图片组，上传教学图片</p>
            </div>
          </Card>
        ) : (
          <div className="space-y-3">
            {pagedList.map((g) => (
              <Card key={g.id} className={!g.enabled ? "opacity-60" : ""}>
                <div className="flex items-center justify-between">
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center gap-2">
                      <h3 className="font-medium text-[#1A1A1A] truncate">{g.name}</h3>
                      <Tag
                        theme={g.enabled ? "success" : "default"}
                        variant="light"
                        size="small"
                      >
                        {g.enabled ? "已启用" : "已禁用"}
                      </Tag>
                      <Tag theme="primary" variant="light" size="small">
                        {g.images.length} 张图片
                      </Tag>
                    </div>
                    {g.description && (
                      <p className="text-xs text-[#63666F] mt-1 truncate">{g.description}</p>
                    )}
                    {/* 缩略图预览（最多 6 张） */}
                    {g.images.length > 0 && (
                      <div className="flex gap-1.5 mt-2 flex-wrap">
                        {g.images.slice(0, 6).map((img) => (
                          // eslint-disable-next-line @next/next/no-img-element
                          <img
                            key={img.id}
                            src={thumbUrl(img.id)}
                            alt={img.description}
                            title="点击放大预览"
                            className="w-12 h-12 object-cover rounded border border-gray-200 cursor-zoom-in hover:opacity-75 transition-opacity"
                            onClick={() => setPreviewImage(img)}
                          />
                        ))}
                        {g.images.length > 6 && (
                          <span className="w-12 h-12 rounded border border-dashed border-gray-300 flex items-center justify-center text-xs text-gray-400">
                            +{g.images.length - 6}
                          </span>
                        )}
                      </div>
                    )}
                    <p className="text-xs text-gray-400 mt-0.5">
                      创建于 {new Date(g.createdAt).toLocaleDateString("zh-CN")}
                    </p>
                    {g.referencedBy && g.referencedBy.length > 0 && (
                      <div className="mt-1.5 flex items-start gap-1 text-xs text-[#63666F]">
                        <Tag theme="warning" variant="light" size="small">
                          被 {g.referencedBy.length} 个课堂引用
                        </Tag>
                        <span className="leading-5 mt-0.5">
                          {g.referencedBy.map((t) => t.title).join("、")}
                        </span>
                      </div>
                    )}
                  </div>
                  <div className="flex items-center gap-1 ml-4 shrink-0">
                    <Button
                      theme={g.enabled ? "warning" : "success"}
                      variant="text"
                      size="small"
                      icon={g.enabled ? <StopCircleIcon /> : <CheckCircleIcon />}
                      onClick={() => handleToggleEnabled(g)}
                    >
                      {g.enabled ? "禁用" : "启用"}
                    </Button>
                    <Button
                      theme="default"
                      variant="text"
                      size="small"
                      icon={<BrowseIcon />}
                      onClick={() => openDetail(g)}
                    >
                      管理图片
                    </Button>
                    <Button
                      theme="default"
                      variant="text"
                      size="small"
                      icon={<AddIcon />}
                      onClick={() => openEdit(g)}
                    >
                      编辑
                    </Button>
                    <Button
                      theme="danger"
                      variant="text"
                      size="small"
                      icon={<DeleteIcon />}
                      onClick={() => setDeleteGroupTarget(g)}
                    />
                  </div>
                </div>
              </Card>
            ))}
          </div>
        )}

        {/* 使用说明 */}
        <div className="p-3 bg-[#F0F7FF] rounded-lg text-xs text-[#63666F]">
          <p>
            <span className="font-medium text-[#0052D9]">📖 使用说明：</span>
            新建图片组并上传教学图片（支持 jpg/png/gif/webp，单张不超过 10MB），上传时 AI
            自动生成图片描述（可在组内修改）；在课堂管理中引用已启用的图片组后，课堂对话中的
            AI 会根据学生问题智能发送组内图片。
          </p>
        </div>

        {/* 分页 */}
        {list.length > 0 && (
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div className="flex items-center gap-2 text-sm text-[#63666F]">
              <span>每页</span>
              <InputNumber
                value={pageSize}
                min={1}
                max={100}
                theme="column"
                onChange={(val) => {
                  const n = Math.max(1, Math.min(100, Number(val) || 1));
                  setPageSize(n);
                  setCurrentPage(1);
                }}
                style={{ width: 72 }}
              />
              <span>个图片组，共 {filteredList.length} 个</span>
            </div>
            <Pagination
              total={filteredList.length}
              pageSize={pageSize}
              current={safePage}
              showJumper
              onChange={(pageInfo) => setCurrentPage(pageInfo.current)}
            />
          </div>
        )}

        {/* 新建/编辑图片组对话框 */}
        <Dialog
          header={editing ? "编辑图片组" : "新建图片组"}
          visible={formVisible}
          onClose={() => {
            setFormVisible(false);
            resetForm();
          }}
          footer={null}
          width={480}
          destroyOnClose
        >
          <div className="space-y-4">
            <Input
              value={formName}
              onChange={(v) => setFormName(v)}
              placeholder="图片组名称 *（如：分数教学图组）"
            />
            <Textarea
              value={formDesc}
              onChange={(v) => setFormDesc(v)}
              placeholder="使用场景说明（选填，如：用于分数概念讲解的示意图）"
              autosize={{ minRows: 2, maxRows: 4 }}
              maxlength={100}
            />
            <div className="flex gap-2 justify-end pt-2 border-t border-gray-100">
              <Button
                onClick={() => {
                  setFormVisible(false);
                  resetForm();
                }}
              >
                取消
              </Button>
              <Button theme="primary" loading={saving} onClick={handleSaveGroup}>
                {editing ? "保存修改" : "创建"}
              </Button>
            </div>
          </div>
        </Dialog>

        {/* 组详情：图片管理对话框 */}
        <Dialog
          header={detailGroup ? `图片组：${detailGroup.name}` : "管理图片"}
          visible={!!detailGroup}
          onClose={() => setDetailGroup(null)}
          footer={<Button onClick={() => setDetailGroup(null)}>关闭</Button>}
          width={860}
          destroyOnClose
        >
          {detailGroup && (
            <div className="space-y-4">
              <div className="flex items-center justify-between">
                <p className="text-xs text-[#63666F]">
                  共 {detailGroup.images.length} 张图片。描述是 AI 判断何时发图的依据，请确保准确。
                </p>
                <div>
                  <input
                    ref={fileInputRef}
                    type="file"
                    accept=".jpg,.jpeg,.png,.gif,.webp,.JPG,.JPEG,.PNG,.GIF,.WEBP"
                    multiple
                    className="hidden"
                    onChange={handleUpload}
                  />
                  <Button
                    theme="primary"
                    size="small"
                    icon={<UploadIcon />}
                    loading={uploading}
                    onClick={() => fileInputRef.current?.click()}
                  >
                    上传图片
                  </Button>
                </div>
              </div>
              {uploading && (
                <div className="flex items-center gap-2 text-xs text-[#0052D9]">
                  <Loading size="small" />
                  正在上传并生成描述（多模态模型自动识别图片内容）...
                </div>
              )}
              {detailGroup.images.length === 0 ? (
                <div className="text-center py-10 text-gray-400">
                  <ImageIcon className="text-3xl" />
                  <p className="text-sm mt-2">暂无图片，点击「上传图片」添加</p>
                </div>
              ) : (
                <div className="grid grid-cols-2 gap-3 max-h-[55vh] overflow-y-auto pr-1">
                  {detailGroup.images.map((img) => {
                    const draft = descDrafts[img.id] ?? img.description;
                    const dirty = draft !== img.description;
                    return (
                      <div
                        key={img.id}
                        className="border border-gray-200 rounded-lg p-2.5 space-y-2"
                      >
                        <div className="flex gap-2.5">
                          {/* eslint-disable-next-line @next/next/no-img-element */}
                          <img
                            src={thumbUrl(img.id)}
                            alt={img.description}
                            title="点击放大预览"
                            className="w-20 h-20 object-cover rounded border border-gray-100 shrink-0 cursor-zoom-in hover:opacity-75 transition-opacity"
                            onClick={() => setPreviewImage(img)}
                          />
                          <div className="flex-1 min-w-0 text-xs text-gray-400 space-y-0.5">
                            <p className="truncate" title={img.originalName}>
                              {img.originalName}
                            </p>
                            <p>{formatFileSize(img.fileSize)}</p>
                            <p>{new Date(img.createdAt).toLocaleDateString("zh-CN")}</p>
                          </div>
                          <Button
                            theme="danger"
                            variant="text"
                            size="small"
                            icon={<DeleteIcon />}
                            onClick={() => handleDeleteImage(img)}
                          />
                        </div>
                        <div className="flex gap-1.5">
                          <Input
                            size="small"
                            value={draft}
                            placeholder="图片描述（AI 发图依据）"
                            onChange={(v) =>
                              setDescDrafts((prev) => ({ ...prev, [img.id]: v as string }))
                            }
                            onBlur={() => handleSaveDesc(img)}
                            maxlength={100}
                          />
                          {dirty && (
                            <Button
                              size="small"
                              theme="primary"
                              variant="outline"
                              onClick={() => handleSaveDesc(img)}
                            >
                              保存
                            </Button>
                          )}
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          )}
        </Dialog>

        {/* 删除图片组确认 */}
        <Dialog
          header="删除图片组"
          visible={!!deleteGroupTarget}
          onClose={() => setDeleteGroupTarget(null)}
          onConfirm={() => deleteGroupTarget && handleDeleteGroup(deleteGroupTarget.id)}
          confirmBtn={{ content: "确定删除", theme: "danger", loading: deleting }}
          cancelBtn={{ content: "取消", disabled: deleting }}
          width={520}
          destroyOnClose
        >
          {deleteGroupTarget && (
            <div className="space-y-3 text-sm text-[#1A1A1A]">
              <p>
                确定删除图片组「
                <span className="font-medium">{deleteGroupTarget.name}</span>
                」及其全部 {deleteGroupTarget.images.length} 张图片吗？此操作不可恢复。
              </p>
              {deleteGroupTarget.referencedBy && deleteGroupTarget.referencedBy.length > 0 ? (
                <div className="p-3 bg-[#FFF3E8] border border-[#FFC69C] rounded-lg">
                  <p className="text-[#D25F00] font-medium mb-1">
                    ⚠ 该图片组正被以下 {deleteGroupTarget.referencedBy.length} 个课堂引用：
                  </p>
                  <p className="text-[#63666F]">
                    {deleteGroupTarget.referencedBy.map((t) => t.title).join("、")}
                  </p>
                  <p className="text-[#63666F] mt-1">
                    删除后这些课堂的对话将无法再发送组内图片。
                  </p>
                </div>
              ) : (
                <p className="text-[#63666F]">该图片组当前未被任何课堂引用。</p>
              )}
            </div>
          )}
        </Dialog>

        {/* 图片放大预览遮罩（z-index 高于 Dialog，详情对话框内点击也可放大） */}
        {previewImage && (
          <div
            className="fixed inset-0 z-[3000] bg-black/75 flex items-center justify-center cursor-zoom-out p-8"
            onClick={() => setPreviewImage(null)}
          >
            <div
              className="flex flex-col items-center gap-3 max-w-full"
              onClick={(e) => e.stopPropagation()}
            >
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img
                src={thumbUrl(previewImage.id)}
                alt={previewImage.description}
                className="max-w-full max-h-[78vh] object-contain rounded-lg shadow-2xl"
              />
              <p className="text-sm text-white/90 bg-black/60 px-4 py-2 rounded-lg max-w-[80vw] truncate">
                {previewImage.originalName}
                {previewImage.description
                  ? ` — ${previewImage.description}`
                  : " —（暂无描述）"}
              </p>
              <p className="text-xs text-white/50">点击空白处关闭</p>
            </div>
          </div>
        )}
      </div>
    </TeacherLayout>
  );
}
