/** 根据年级判断学段 */
export function getStage(grade: string): Stage {
  return grade.includes("高中") ? "高中" : "义务教育";
}

/**
 * 获取某年级+学科的核心素养。
 * 查找顺序：本学段课标 → 本学段别名 → 跨学段兜底 → 相邻学段同科。
 * 找不到返回 null。
 */
export function getSubjectCompetencies(grade: string, subject: string): SubjectCompetencies | null {
  const stage = getStage(grade);
  const table = stage === "高中" ? senior : compulsory;
  const otherTable = stage === "高中" ? compulsory : senior;

  if (table[subject]) {
    return { stage, subject, ...table[subject] };
  }

  const alias = stageAliases[stage][subject];
  if (alias && table[alias.subject]) {
    return { stage, subject, ...table[alias.subject], note: alias.note };
  }

  const cross = crossFallback[stage][subject];
  if (cross && otherTable[cross.subject]) {
    return { stage, subject, ...otherTable[cross.subject], note: cross.note };
  }

  if (otherTable[subject]) {
    return {
      stage,
      subject,
      ...otherTable[subject],
      note: "该学科与所选学段的组合较少见，已按相邻学段课程标准的核心素养处理",
    };
  }

  return null;
}

/* ==================== 生成结果结构校验 ==================== */

export interface ObjectivesValidation {
  /** 是否通过校验 */
  valid: boolean;
  /** 解析出的目标条数 */
  count: number;
  /** 期望的目标条数（= 素养维度数） */
  expected: number;
  /** 解析出的行首素养标签序列（按行序） */
  dimensions: string[];
  /** 重复出现的维度名 */
  duplicates: string[];
  /** 不在素养清单中的维度名 */
  unknown: string[];
  /** 缺少行首【素养名称】标注的目标行序号 */
  missingLabelLines: number[];
}

/**
 * 校验 AI 生成的课堂目标是否与素养维度严格一一对应：
 * - 目标条数 === 素养维度数
 * - 每条目标行首有【素养名称】标签，且在清单内
 * - 同一维度不得出现两次
 */
export function validateObjectiveDimensions(
  text: string,
  competencies: Competency[]
): ObjectivesValidation {
  // 目标行：以数字编号开头（1. / 1、/ 1．）
  const objectiveLines = text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => /^\d+\s*[.、．]/.test(l));

  const labelRe = /^\d+\s*[.、．]\s*\**\s*【([^】]+)】/;
  const dimensions: string[] = [];
  const missingLabelLines: number[] = [];
  objectiveLines.forEach((line, idx) => {
    const m = line.match(labelRe);
    if (m) dimensions.push(m[1].trim());
    else missingLabelLines.push(idx + 1);
  });

  const validNames = new Set(competencies.map((c) => c.name));
  const seen = new Set<string>();
  const duplicates: string[] = [];
  const unknown: string[] = [];
  for (const d of dimensions) {
    if (!validNames.has(d)) unknown.push(d);
    else if (seen.has(d)) duplicates.push(d);
    else seen.add(d);
  }

  const expected = competencies.length;
  return {
    valid:
      objectiveLines.length === expected &&
      missingLabelLines.length === 0 &&
      duplicates.length === 0 &&
      unknown.length === 0,
    count: objectiveLines.length,
    expected,
    dimensions,
    duplicates,
    unknown,
    missingLabelLines,
  };
}

/** 将校验结果转为可读的问题描述 */
export function describeValidationIssues(v: ObjectivesValidation): string {
  const issues: string[] = [];
  if (v.count !== v.expected) issues.push(`目标条数为 ${v.count} 条，应为 ${v.expected} 条`);
  if (v.duplicates.length) issues.push(`素养维度重复：${[...new Set(v.duplicates)].join("、")}`);
  if (v.unknown.length) issues.push(`清单外素养名称：${[...new Set(v.unknown)].join("、")}`);
  if (v.missingLabelLines.length)
    issues.push(`第 ${v.missingLabelLines.join("、")} 条缺少【素养名称】标注`);
  return issues.join("；") || "未知问题";
}
