/** 带声调符号的字符（教学注音的强信号） */
const TONE_MARK_RE = /[āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜê]/;

/** 候选拼音串：拉丁字母 + ü 及其四声 + 声调字符 */
const PINYIN_TOKEN_RE = /[a-züāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜê]+/gi;

/**
 * 贪心拆分：把一串拼音（可能含多个音节，如 shǎngwǔ）按最长匹配拆成
 * 表内的单音节序列；任一前缀拆不动则整体放弃（保留原样）。
 */
function splitSyllables(tok: string): string[] | null {
  const out: string[] = [];
  let rest = tok.toLowerCase();
  while (rest.length > 0) {
    let matched = false;
    for (let len = Math.min(6, rest.length); len >= 1; len--) {
      const part = rest.slice(0, len);
      if (PINYIN_TO_HANZI[part]) {
        out.push(part);
        rest = rest.slice(len);
        matched = true;
        break;
      }
    }
    if (!matched) return null;
  }
  return out;
}

/**
 * 把朗读文本中的拼音注音替换成读音对应的汉字。
 * 只处理**带声调符号**的拼音串；表外或无声调串保持原样（不劣于现状）。
 */
export function replacePinyinWithHanzi(text: string): string {
  return text.replace(PINYIN_TOKEN_RE, (tok) => {
    if (!TONE_MARK_RE.test(tok)) return tok; // 无声调：可能是英文单词，不动
    const syllables = splitSyllables(tok);
    if (!syllables) return tok;
    return syllables.map((s) => PINYIN_TO_HANZI[s]).join("");
  });
}
