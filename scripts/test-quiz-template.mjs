const BASE = "http://localhost:3000";
const SUB_ID = "cms05ta5u000eeius9k9iq9n2";

async function login() {
  const res = await fetch(`${BASE}/api/auth/login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ phone: "13338183337", password: "123456" }),
  });
  const data = await res.json();
  if (!res.ok) { console.error("登录失败", data); process.exit(1); }
  console.log("登录成功, token 长度", (data.token || "").length);
  return data.token;
}

async function main() {
  const token = await login();
  const headers = { "Content-Type": "application/json", Authorization: `Bearer ${token}` };

  const tplRes = await fetch(`${BASE}/api/analysis-templates`, { headers }).then((r) => r.json());
  const quizTpls = (tplRes.all || []).filter((t) => t.type === "QUIZ_DESIGN");
  console.log("QUIZ_DESIGN 模板数:", quizTpls.length, quizTpls.map((t) => t.name));
  const tpl = quizTpls[0];
  if (!tpl) { console.error("没有 QUIZ_DESIGN 模板，无法继续"); process.exit(1); }

  // 1. 无模板创建 -> 期望 400
  const noTpl = await fetch(`${BASE}/api/quiz-activities`, {
    method: "POST", headers,
    body: JSON.stringify({ subProjectId: SUB_ID, title: "自动化测试-无模板", autoGenerate: true }),
  });
  const noTplText = await noTpl.text();
  console.log("【用例1】无模板创建 ->", noTpl.status, noTplText);

  // 2. 有模板创建 -> 期望 201
  const withTpl = await fetch(`${BASE}/api/quiz-activities`, {
    method: "POST", headers,
    body: JSON.stringify({
      subProjectId: SUB_ID,
      title: "自动化测试-有模板",
      autoGenerate: true,
      quizDesignTemplateId: tpl.id,
      quizDesignTemplateContent: tpl.content,
    }),
  });
  const withData = await withTpl.json();
  console.log("【用例2】有模板创建 ->", withTpl.status, "autoGenerated:", withData.autoGenerated, "count:", withData.count);

  // 3. 普通创建（无自动生成）-> 期望 201 count 0
  const manual = await fetch(`${BASE}/api/quiz-activities`, {
    method: "POST", headers,
    body: JSON.stringify({ subProjectId: SUB_ID, title: "自动化测试-手动", autoGenerate: false }),
  });
  const manualData = await manual.json();
  console.log("【用例3】手动创建 ->", manual.status, "autoGenerated:", manualData.autoGenerated, "count:", manualData.count);
}

main().catch((e) => { console.error(e); process.exit(1); });
